package com.kapp.tidings.desktop

/**
 * `--headless`：只跑运行时 + 控制面，不组合任何 Compose。
 *
 * ## 为什么这个开关值得存在（而且不该被当成"用户设置"）
 *
 * 它回答两个本仓必须能回答、但用别的办法答不了的问题：
 *
 * 1. **守护进程形态要多少内存。** 方案里「守护 / UI 两进程」那一阶段的前提是
 *    "拆掉 UI 之后常驻能降到多少"。没有这个开关，那个数只能推算 —— 而本仓的规矩
 *    是测（并且读数必须能复现）。
 * 2. **UI 是不是真的只是观察者。** 如果去掉 UI 之后进程还能收发消息、控制面还能
 *    应答 `/healthz` 与 `/v1/inbox`，那"领域层不依赖 UI"这件事就是**成立**的；
 *    反过来，只要去掉 UI 就什么都干不了，那分层只是名义上的。
 *
 * ## 它为什么不是产品功能
 *
 * 用户没有理由要一个没有界面的捎话（托盘常驻才是产品形态）。所以这个开关
 * **不暴露给界面、不写进文档的用户章节**，只在测内存与判分层时用。
 */
internal object HeadlessMode {

    /**
     * 命令行标记。
     *
     * 用 `--headless` 而不是 `--background` 的变体：后者已经是"托盘驻留"这个
     * **产品行为**的开关（登录自启用它），把一个"完全不画界面"的调试语义塞进去，
     * 会让登录自启在某个分支上变成"开机后什么都没有"。
     */
    const val FLAG: String = "--headless"

    /** 这一组参数是不是要跑无界面形态。 */
    fun requested(args: List<String>): Boolean = args.any { it == FLAG }
}
